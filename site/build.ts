// Builds the course website into site/dist.
//
//   bun site/build.ts                 build everything
//   bun site/build.ts --registry-only only regenerate the scene registry
//
// Lessons are read from the day-* folders, LeetCode problems from
// leetcode/NNNN-slug folders. Every animation referenced by a page is
// checked with validateScene before anything is written.

import { mkdir, readdir, rm } from "node:fs/promises";
import { basename, join } from "node:path";
import { validateScene } from "./src/client/player/snapshots.ts";
import type { Scene } from "./src/client/player/types.ts";
import { renderMarkdown, stripTags } from "./src/markdown.ts";
import {
  type DayInfo,
  docPage,
  homePage,
  leetcodeIndexPage,
  lessonPage,
  type ProblemInfo,
  problemPage,
  SITE,
} from "./src/templates.ts";

const ROOT = join(import.meta.dir, "..");
const SITE_DIR = import.meta.dir;
const DIST = join(SITE_DIR, "dist");
const SCENES_DIR = join(SITE_DIR, "src/client/player/scenes");
const REGISTRY = join(SCENES_DIR, "registry.generated.ts");

// ---------------------------------------------------------------------------
// Scenes

async function sceneFiles(): Promise<string[]> {
  const names = await readdir(SCENES_DIR);
  return names
    .filter((name) => name.endsWith(".ts") && name !== "registry.generated.ts")
    .sort();
}

async function writeRegistry(files: string[]): Promise<void> {
  const lines = files.map((file) => {
    const id = file.replace(/\.ts$/, "");
    return `  "${id}": () => import("./${file}"),`;
  });
  const source = `// Generated by site/build.ts. Do not edit: add a file to this folder instead.
import type { Scene } from "../types.ts";

export const sceneLoaders: Record<string, () => Promise<{ default: Scene }>> = {
${lines.join("\n")}
};
`;
  await Bun.write(REGISTRY, source);
}

async function loadScenes(files: string[]): Promise<Map<string, Scene>> {
  const scenes = new Map<string, Scene>();
  const problems: string[] = [];
  for (const file of files) {
    const module: { default?: Scene } = await import(join(SCENES_DIR, file));
    const scene = module.default;
    const expected = file.replace(/\.ts$/, "");
    if (!scene) {
      problems.push(`${file}：沒有 export default 一個 Scene`);
      continue;
    }
    if (scene.id !== expected) {
      problems.push(`${file}：id 是「${scene.id}」，但檔名要求「${expected}」`);
    }
    for (const problem of validateScene(scene))
      problems.push(`${file}：${problem}`);
    scenes.set(scene.id, scene);
  }
  if (problems.length > 0) {
    throw new Error(`動畫場景有問題：\n  ${problems.join("\n  ")}`);
  }
  return scenes;
}

// ---------------------------------------------------------------------------
// Content discovery

async function readText(path: string): Promise<string> {
  return Bun.file(path).text();
}

/** "| ☐ | [05](day-05-x/README.md) | 主題 | Todo 進度 |" rows in the root README. */
function mainlineFromReadme(readme: string): Map<string, string> {
  const result = new Map<string, string>();
  for (const line of readme.split("\n")) {
    const match =
      /^\|\s*[☐☑]\s*\|\s*\[\d+\]\((day-[^/]+)\/README\.md\)\s*\|[^|]*\|\s*([^|]*?)\s*\|/.exec(
        line,
      );
    if (match?.[1] && match[2] !== undefined) {
      result.set(
        match[1],
        match[2] === "—" ? "" : stripTags(Bun.markdown.html(match[2])).trim(),
      );
    }
  }
  return result;
}

async function discoverDays(): Promise<DayInfo[]> {
  const folders = (await readdir(ROOT))
    .filter((name) => /^day-\d\d-/.test(name))
    .sort();
  const mainline = mainlineFromReadme(await readText(join(ROOT, "README.md")));
  const days: DayInfo[] = [];
  for (const folder of folders) {
    const source = await readText(join(ROOT, folder, "README.md"));
    const heading = /^# Day (\d+) — (.+)$/m.exec(source);
    if (!heading?.[1] || !heading[2])
      throw new Error(`${folder}/README.md 的第一行要是「# Day NN — 主題」`);
    const number = Number(heading[1]);
    const lead = /^# .+\n\n> (.+)$/m.exec(source)?.[1];
    days.push({
      number,
      label: heading[1].padStart(2, "0"),
      folder,
      slug: `day-${heading[1].padStart(2, "0")}`,
      title: heading[2].trim(),
      lead,
      week: number <= 7 ? 1 : 2,
      mainline: mainline.get(folder) ?? "",
    });
  }
  return days;
}

async function discoverProblems(): Promise<ProblemInfo[]> {
  const dir = join(ROOT, "leetcode");
  let folders: string[] = [];
  try {
    folders = (await readdir(dir))
      .filter((name) => /^\d{4}-[a-z0-9-]+$/.test(name))
      .sort();
  } catch {
    return [];
  }
  const problems: ProblemInfo[] = [];
  for (const name of folders) {
    const source = await readText(join(dir, name, "README.md"));
    const title = /^# (.+)$/m.exec(source)?.[1]?.trim() ?? name;
    const lead = /^# .+\n\n> (.+)$/m.exec(source)?.[1];
    const id = Number(
      /LeetCode (\d+)/.exec(lead ?? "")?.[1] ?? name.slice(0, 4),
    );
    const afterDay = /Day (\d+)/.exec(lead ?? "")?.[1];
    problems.push({
      folder: `leetcode/${name}`,
      slug: name,
      id,
      title: stripTags(Bun.markdown.html(title)).trim(),
      lead,
      afterDay: afterDay ? Number(afterDay) : undefined,
      technique: /技巧：([^｜]+)/.exec(lead ?? "")?.[1]?.trim() ?? "",
      leetcodeUrl: `https://leetcode.com/problems/${name.slice(5)}/`,
    });
  }
  // Learning order: by the lesson after which each problem is recommended.
  return problems.sort(
    (a, b) => (a.afterDay ?? 99) - (b.afterDay ?? 99) || a.id - b.id,
  );
}

// ---------------------------------------------------------------------------
// Build

async function writePage(path: string, html: string): Promise<void> {
  await mkdir(join(DIST, path), { recursive: true });
  await Bun.write(join(DIST, path, "index.html"), html);
}

async function build(): Promise<void> {
  const started = performance.now();
  const files = await sceneFiles();
  await writeRegistry(files);
  if (process.argv.includes("--registry-only")) {
    console.log(`已產生動畫索引（${files.length} 個場景）`);
    return;
  }
  const scenes = await loadScenes(files);

  const days = await discoverDays();
  const problems = await discoverProblems();

  const pageFor = (repoPath: string): string | undefined => {
    const clean = repoPath.replace(/\/README\.md$/, "").replace(/\/$/, "");
    if (clean === "README.md" || clean === "" || clean === ".") return "";
    if (clean === "ROADMAP.md") return "roadmap/";
    const day = days.find((item) => item.folder === clean);
    if (day) return `${day.slug}/`;
    if (clean === "leetcode") return "leetcode/";
    const problem = problems.find((item) => item.folder === clean);
    if (problem) return `leetcode/${problem.slug}/`;
    return undefined;
  };
  const linkContext = (sourcePath: string, depth: number) => ({
    sourcePath,
    depth,
    pageFor,
    repoUrl: SITE.repoUrl,
    siteUrl: SITE.siteUrl,
  });

  await rm(DIST, { recursive: true, force: true });
  await mkdir(join(DIST, "assets"), { recursive: true });

  const used = new Map<string, string>();
  const unknown: string[] = [];
  const track = (pageName: string, ids: string[]): void => {
    for (const id of ids) {
      if (!scenes.has(id))
        unknown.push(`${pageName} 用到不存在的動畫「${id}」`);
      used.set(id, pageName);
    }
  };

  for (const day of days) {
    const sourcePath = `${day.folder}/README.md`;
    const doc = renderMarkdown(
      await readText(join(ROOT, sourcePath)),
      linkContext(sourcePath, 1),
    );
    track(day.slug, doc.animations);
    await writePage(day.slug, lessonPage(days, day, doc.html, doc.headings));
  }

  for (const problem of problems) {
    const sourcePath = `${problem.folder}/README.md`;
    const doc = renderMarkdown(
      await readText(join(ROOT, sourcePath)),
      linkContext(sourcePath, 2),
    );
    track(problem.slug, doc.animations);
    await writePage(
      `leetcode/${problem.slug}`,
      problemPage(problems, problem, doc.html),
    );
  }

  const leetcodeReadme = join(ROOT, "leetcode/README.md");
  if (await Bun.file(leetcodeReadme).exists()) {
    const doc = renderMarkdown(
      await readText(leetcodeReadme),
      linkContext("leetcode/README.md", 1),
    );
    track("leetcode", doc.animations);
    await writePage(
      "leetcode",
      leetcodeIndexPage(doc.html, doc.title, problems),
    );
  }

  const roadmap = renderMarkdown(
    await readText(join(ROOT, "ROADMAP.md")),
    linkContext("ROADMAP.md", 1),
  );
  await writePage(
    "roadmap",
    docPage({
      title: roadmap.title,
      html: roadmap.html,
      depth: 1,
      page: "roadmap",
      active: "roadmap",
    }),
  );

  track("home", ["day03-count-done"]);
  await Bun.write(join(DIST, "index.html"), homePage(days, problems));
  await Bun.write(
    join(DIST, "404.html"),
    docPage({
      title: "找不到這一頁",
      html: `<p>網址可能打錯了，或這一頁已經搬家。</p><p><a href="${SITE.siteUrl}/">回到課程首頁</a></p>`,
      depth: 0,
      page: "404",
    }).replace(/(href|src)="assets\//g, `$1="${SITE.siteUrl}/assets/`),
  );

  if (unknown.length > 0) throw new Error(unknown.join("\n"));
  const unused = [...scenes.keys()].filter((id) => !used.has(id));
  if (unused.length > 0)
    console.warn(`提醒：這些動畫沒有任何頁面使用：${unused.join("、")}`);

  const result = await Bun.build({
    entrypoints: [join(SITE_DIR, "src/client/main.ts")],
    outdir: join(DIST, "assets"),
    target: "browser",
    format: "esm",
    splitting: true,
    minify: true,
    naming: { entry: "[name].[ext]", chunk: "chunks/[name]-[hash].[ext]" },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("打包瀏覽器程式失敗");
  }
  await Bun.write(
    join(DIST, "assets/site.css"),
    Bun.file(join(SITE_DIR, "src/styles.css")),
  );
  await Bun.write(
    join(DIST, "assets/favicon.svg"),
    Bun.file(join(SITE_DIR, "src/favicon.svg")),
  );
  await Bun.write(join(DIST, ".nojekyll"), "");

  const pages = days.length + problems.length + 4;
  const seconds = ((performance.now() - started) / 1000).toFixed(1);
  console.log(
    `網站建置完成：${pages} 頁、${scenes.size} 個動畫（${used.size} 個有頁面使用），${seconds} 秒，輸出在 ${basename(SITE_DIR)}/dist`,
  );
}

await build();
